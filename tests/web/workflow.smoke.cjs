// Real browser and HTTP/SQLite workflows; explicitly fake Agent/environment, no Docker or model.
const { spawn } = require("node:child_process");
const { createInterface } = require("node:readline");
const assert = require("node:assert/strict");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
(async () => {
  const server = spawn("uv", ["run", "--locked", "python", "-m", "tests.web.workflow_fixture"], { stdio: ["ignore", "pipe", "inherit"] });
  let browser;
  try {
    const info = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("fixture startup timeout")), 20000);
      createInterface({input: server.stdout}).once("line", line => { clearTimeout(timer); resolve(JSON.parse(line)); });
      server.once("exit", code => reject(new Error(`fixture exited ${code}`)));
    });
    browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, args: ["--no-sandbox"] });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], bodies = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("response", async response => { if(response.url().includes("/api/")) { try { bodies.push(await response.text()); } catch {} } });
    const base = `http://127.0.0.1:${info.port}`;
    await page.goto(`${base}/#token=web-workflow-fixture-not-a-production-secret`);
    await page.getByRole("link", {name:"科研项目",exact:true}).click();
    await page.getByRole("heading", {name:"旧科研项目",exact:true}).waitFor();
    await page.goto(`${base}/#projects/${info.legacy}`);
    await page.getByRole("heading", {name:"工作区未绑定",exact:true}).waitFor();
    await page.getByLabel("已有工作区").selectOption(info.project);
    await page.getByRole("button", {name:"确认关联此工作区"}).click();
    await page.getByRole("heading", {name:"研究背景与方案",exact:true}).waitFor();
    await page.getByText("Fixture 均值为 2", {exact:true}).waitFor();
    await page.getByText("编译任务 / 更新材料快照", {exact:true}).click();
    await page.getByLabel("执行配置（项目内 YAML 路径）").fill("configs/experiments/pilot.yaml");
    await page.getByRole("button", {name:"编译材料快照"}).click();
    await page.getByLabel("Codex 模型").fill("explicit-fixture");
    await page.getByLabel("允许本次实验联网（模型访问需要）").check();
    assert(await page.getByRole("button", {name:"确认提交一次实验"}).isDisabled());
    await page.getByRole("button", {name:"检查环境与资源"}).click();
    await page.getByText("预检通过", {exact:true}).waitFor();
    await page.getByText(/CPU 1 核 · 内存 0.3 GiB · GPU 0/).waitFor();
    await page.getByLabel("运行时限（秒）").fill("90");
    assert(await page.getByRole("button", {name:"确认提交一次实验"}).isDisabled());
    await page.getByRole("button", {name:"检查环境与资源"}).click();
    let lostReply = true;
    const operations = [];
    await page.route("**/api/v1/projects/*/submit", async route => {
      operations.push(route.request().postDataJSON().operation_id);
      const response = await route.fetch();
      if (lostReply) { lostReply = false; await route.abort("failed"); }
      else await route.fulfill({response});
    });
    await page.getByRole("button", {name:"确认提交一次实验"}).click();
    await page.getByRole("alert").filter({hasText:"Failed to fetch"}).waitFor();
    await page.getByRole("button", {name:"确认提交一次实验"}).click();
    await page.waitForURL(/#execution\//);
    assert.equal(operations.length, 2);
    assert.equal(operations[0], operations[1]);
    const submitted = page.url();
    await page.reload();
    await page.getByRole("heading", {name:"运行状态",exact:true}).waitFor();
    assert.equal(page.url(), submitted);
    await page.getByRole("button", {name:"取消运行",exact:true}).click();
    await page.getByText("执行结果：cancelled", {exact:true}).waitFor();
    await page.goto(`${base}/#execution/${info.finished}`);
    await page.getByRole("heading", {name:"容器内 Job",exact:true}).waitFor();
    await page.getByRole("button", {name:/metrics.json ·/}).click();
    await page.getByRole("button", {name:"预览",exact:true}).click();
    await page.getByText('{"mean": 2.0}', {exact:true}).waitFor();
    const download = page.waitForEvent("download");
    await page.getByRole("button", {name:"下载",exact:true}).click();
    assert.equal((await download).suggestedFilename(), "metrics.json");
    await page.screenshot({path:"/tmp/agent-infra-w-results.png",fullPage:true});
    await page.goto(`${base}/#projects/${info.project}`);
    await page.getByRole("heading", {name:"结果分析",exact:true}).waitFor();
    await page.screenshot({path:"/tmp/agent-infra-w-project.png",fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:"/tmp/agent-infra-w-mobile.png",fullPage:true});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.goto(`${base}/#projects`);
    await page.getByRole("button", {name:"＋ 新建项目"}).click();
    await page.getByLabel("项目名称",{exact:true}).fill("Web 初始化验证");
    await page.getByLabel("研究目标",{exact:true}).fill("仅验证初始化，不调用模型");
    await page.getByLabel("服务器工作区路径").fill(`${info.root}/new-workspace`);
    await page.getByRole("button",{name:"创建工作区",exact:true}).click();
    await page.getByRole("heading",{name:"Web 初始化验证",exact:true}).waitFor();
    await page.reload();
    await page.getByRole("heading",{name:"Web 初始化验证",exact:true}).waitFor();
    assert.equal(errors.length,0,errors.join("\n"));
    assert(!bodies.join("\n").includes("PRIVATE_W_SENTINEL"));
    await page.getByRole("button",{name:"退出连接"}).click();
    console.log("W browser passed: legacy binding, shared init, compilation, preflight invalidation, submit/reload/cancel, metrics preview/download, analysis, Job separation, mobile, private filtering.");
  } finally {
    await browser?.close();
    server.kill("SIGTERM");
  }
})().catch(error => {console.error(error);process.exitCode=1;});
