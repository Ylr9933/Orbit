// Browser acceptance uses synthetic persisted batches and real HTTP/Records APIs.
const { spawn } = require('node:child_process');
const { createInterface } = require('node:readline');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const server = spawn('uv', ['run', '--locked', 'python', 'tests/web/benchmark_fixture.py'], { stdio: ['ignore', 'pipe', 'inherit'] });
  let browser;
  try {
    const info = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('fixture startup timeout')), 20000);
      createInterface({ input: server.stdout }).once('line', line => { clearTimeout(timer); resolve(JSON.parse(line)); });
      server.once('exit', code => reject(new Error(`fixture exited ${code}`)));
    });
    browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, args: ['--no-sandbox'] });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await context.newPage();
    const errors = [], bodies = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', async r => { if (r.url().includes('/api/')) try { bodies.push(await r.text()); } catch {} });
    const base = `http://127.0.0.1:${info.port}`;
    await page.goto(`${base}/#benchmarks/workspace?batch=${info.right}&baseline=${info.left}&metric=score`);
    await page.getByLabel('访问令牌', { exact: true }).fill('benchmark-browser-fixture-token-123456789');
    await page.getByRole('button', { name: '连接控制台' }).click();
    await page.getByRole('heading', { name: '任务结果', exact: true }).waitFor();
    assert(await page.getByText('60 / 60 个任务', { exact: false }).count());
    await page.getByRole('button', { name: '下一页任务' }).click();
    await page.getByRole('cell', { name: 'task-059', exact: true }).last().waitFor();
    await page.getByLabel('搜索任务', { exact: true }).fill('task-000');
    await page.getByRole('link', { name: '查看详情', exact: true }).waitFor();
    const chartDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出图表', exact: true }).click();
    assert.equal((await chartDownload).suggestedFilename(), 'benchmark-trend.svg');
    const csvDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出对比 CSV' }).click();
    assert.equal((await csvDownload).suggestedFilename(), 'benchmark-comparison.csv');
    await page.getByText('实验名称、说明与标签', { exact: true }).click();
    await page.getByLabel('实验名称', { exact: true }).fill('Prompt revision');
    await page.getByLabel('实验笔记', { exact: true }).fill('Improved output format; verify on another seed.');
    await page.getByRole('button', { name: '保存笔记' }).click();
    await page.getByRole('status').filter({ hasText: '已保存' }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Prompt revision', exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/benchmark-web-comparison.png', fullPage: true });
    await page.getByLabel('搜索对比任务').fill('task-000');
    await page.getByRole('link', { name: '并排查看轨迹' }).click();
    await page.getByRole('heading', { name: '基线实验', exact: true }).waitFor();
    await page.getByLabel('搜索轨迹', { exact: true }).last().waitFor();
    await page.waitForFunction(() => document.querySelectorAll('input[placeholder="命令、错误或输出内容"]').length === 2);
    assert.equal(await page.getByLabel('搜索轨迹', { exact: true }).count(), 2);
    await page.getByLabel('搜索轨迹', { exact: true }).last().fill('DEEP_ERROR');
    await page.getByText('DEEP_ERROR: missing column', { exact: true }).waitFor();
    await page.getByRole('button', { name: '复制步骤链接' }).last().click();
    const deep = await page.evaluate(() => navigator.clipboard.readText());
    await page.goto(deep);
    await page.getByText('DEEP_ERROR: missing column', { exact: true }).waitFor();
    await page.getByRole('button', { name: '文件与评分证据' }).last().click();
    await page.getByLabel('搜索证据文件').fill('score.json');
    await page.getByRole('button', { name: '预览', exact: true }).click();
    await page.getByText('"score": 0', { exact: false }).waitFor();
    const fileDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: '下载', exact: true }).click();
    assert.equal((await fileDownload).suggestedFilename(), 'score.json');
    await page.screenshot({ path: '/tmp/benchmark-web-evidence.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '/tmp/benchmark-web-mobile.png', fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.goto(`${base}/#benchmarks`);
    await page.getByText('登记已有批次', { exact: true }).click();
    await page.getByLabel('批次目录', { exact: true }).fill(info.third);
    await page.getByRole('button', { name: '登记批次', exact: true }).click();
    await page.getByRole('heading', { name: 'incomplete', exact: true }).waitFor();
    await page.getByLabel('结果筛选').selectOption('unscored');
    await page.getByText('2 / 60 个任务', { exact: false }).waitFor();
    assert(!bodies.join('\n').includes('PRIVATE_NATIVE_SENTINEL'));
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('Benchmark browser passed: 60 tasks, pairing/trend, notes/reload, comparison, trace search/deep link, files/downloads, registration, incomplete results and mobile.');
  } finally {
    await browser?.close(); server.kill('SIGTERM');
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
